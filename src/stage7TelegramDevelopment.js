import {labelForCategory} from './journal.js';
import {createStage7Development} from './stage7Development.js';
import {createSyntheticJournalTelegram,createStage7Dispatcher} from './stage7Dispatcher.js';
import {createUpdateProcessor} from './bot/updateProcessor.js';
import {createSettings} from './bot/settings.js';
import {JOURNAL_COPY,presentationLocale} from './stage7Registry.js';

/** Fully wired synthetic Telegram path using the existing update claim, private
 * identity, conversation lane, ACK and durable reply delivery infrastructure.
 * No production entry point imports this composition or supplies its hooks. */
export async function createStage7TelegramDevelopment({core,stores,db,provider=createSyntheticJournalTelegram(),now=core.now}){
 const companion=await createStage7Development({core,stores,db}),settings=createSettings({db,now}),acks=[];
 const journalReply=async({user,chatId,reply})=>{
  if(!reply)return null;
  const actor=await companion.interactions.authenticate({user,chatId});
  if(reply.stage7View==='WEEKLY'){const fresh=await companion.weekly.build(actor);return {text:fresh.text,editMessageId:reply.editMessageId,replyMarkup:{inline_keyboard:[]},stage7SourceFacts:fresh.sourceFactIds,stage7SourceInteractions:fresh.sourceInteractionIds,stage7SourceEvidence:fresh.sourceEvidenceIds};}
  if(!reply.stage7InteractionId)return reply;
  const row=await companion.interactions.read(user.id,reply.stage7InteractionId);
  if(!row||row.revision!==reply.stage7Revision)return companion.interactions.expired(actor);
  // Recent view is regenerated by an authenticated fresh journal request below.
  if(reply.stage7View==='RECENT'){
   const facts=await companion.ownFacts(actor),locale=presentationLocale(await db.getLocale(user.id)),c=JOURNAL_COPY[locale];
   return {...reply,text:facts.length?facts.slice(0,10).map(f=>`${f.health_date} · ${labelForCategory(f.category,locale)} · ${f.exposure_state==='CONFIRMED_UNEXPOSED'?c.no:c.yes}`).join('\n'):c.empty};
  }
  return companion.card(actor,row);
 };
 const processor=createUpdateProcessor({db,now,resolveUser:chatId=>db.resolveUserByChatId(chatId),
  stage7Inbound:async input=>{
   const reply=await companion.handle({...input,requestKey:String(input.updateId)})??await companion.handleNote(input);
   return reply?{handled:true,reply}:null;
  },stage7Reply:journalReply,
  handleMessage:input=>settings(input),
  answerCallback:async id=>{acks.push(id);},
  sendReply:async({reply,userId,chatId})=>{
   const card=await provider.send({...reply,chatId});
   if(/^\d+$/.test(card?.messageId??'')&&reply.stage7InteractionId){const user=await db.getUser(userId),actor=await companion.interactions.authenticate({user,chatId});await companion.interactions.bind(actor,reply.stage7InteractionId,reply.editMessageId??card.messageId);}
   return {sent:true,messageId:card?.messageId};
  },
 });
 const dispatcher=createStage7Dispatcher({core,db,companion,provider});
 return {companion,processor,dispatcher,acks,provider,
  // Scheduler/recovery calls this separately after ordinary briefing completion.
  reconcileDaily:async({user,chatId,healthDay,signal=null,metricSeries=[]})=>{
   const result=await companion.prepareAfterBrief({user,chatId,healthDay,signal,metricSeries});
   return result.deliveryId?dispatcher.dispatch({user,chatId,deliveryId:result.deliveryId}):result;
  }};
}
